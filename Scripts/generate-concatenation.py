#!/usr/bin/env python3
"""Writes Sources/TupleKit/Extension/Tuple+Concatenation.swift, or with --check verifies it is current.

Swift 6.4.2 cannot unify a result type that joins two parameter packs, such as
Tuple<repeat each Left, repeat each Right>, with a concrete Tuple type. Each overload
therefore joins one pack with a fixed number of right-hand members.
"""
import pathlib
import sys

MAX_RIGHT_ARITY = 6
EXAMPLE = ['1', '"a"', '2.5', '3', '"b"', 'false']
output = pathlib.Path(__file__).resolve().parent.parent / 'Sources/TupleKit/Extension/Tuple+Concatenation.swift'

LINE_LIMIT = 100


def construction(result, members):
    """Builds the result tuple on one line, or in swift-format's nested layout when too long."""
    line = f"    {result}(members: ({', '.join(members)}))"
    if len(line) <= LINE_LIMIT:
        return [line]
    items = [f'        {member},' for member in members[:-1]] + [f'        {members[-1]}']
    return [f'    {result}(', '      members: (', *items, '      )', '    )']


lines = [
    '// Generated by Scripts/generate-concatenation.py. Do not edit.',
    '',
    'extension Tuple {',
    '  /// Returns the left tuple unchanged, because the right tuple has no members.',
    '  ///',
    '  /// ```swift',
    '  /// let same = Tuple(1, "a") + Tuple()',
    '  /// // same is Tuple(1, "a")',
    '  /// ```',
    '  ///',
    '  /// - Parameters:',
    '  ///   - lhs: The tuple to return.',
    '  ///   - rhs: An empty tuple.',
    '  /// - Returns: `lhs`.',
    '  public static func + (lhs: Self, rhs: Tuple<>) -> Self {',
    '    lhs',
    '  }',
]
for arity in range(1, MAX_RIGHT_ARITY + 1):
    right = [f'Right{index}' for index in range(arity)]
    result = f"Tuple<{', '.join(['repeat each Member'] + right)}>"
    members = ['rhs.members'] if arity == 1 else [f'rhs.members.{index}' for index in range(arity)]
    example = ', '.join(EXAMPLE[:arity])
    lines += [
        '',
        f"  /// Concatenates a tuple with a {arity}-member tuple, keeping every member's static type.",
        '  ///',
        '  /// The result holds the members of `lhs` followed by the members of `rhs`, in order.',
        '  /// Overloads exist for right-hand tuples of up to six members. On Swift 6.4.2, an',
        '  /// expression with four or more `+` operands fails to type-check, so concatenate',
        '  /// longer chains in steps.',
        '  ///',
        '  /// ```swift',
        f'  /// let joined = Tuple(true) + Tuple({example})',
        f'  /// // joined is Tuple(true, {example})',
        '  /// ```',
        '  ///',
        '  /// - Parameters:',
        '  ///   - lhs: The tuple whose members come first.',
        '  ///   - rhs: The tuple whose members come last.',
        '  /// - Returns: A tuple with the members of both tuples, in order.',
    ]
    signature = f"  public static func + <{', '.join(right)}>(lhs: Self, rhs: Tuple<{', '.join(right)}>) -> {result} {{"
    if len(signature) <= LINE_LIMIT:
        lines.append(signature)
    else:
        lines += [
            f"  public static func + <{', '.join(right)}>(",
            '    lhs: Self,',
            f"    rhs: Tuple<{', '.join(right)}>",
            f'  ) -> {result} {{',
        ]
    lines += construction(result, ['repeat each lhs.members', *members])
    lines.append('  }')
lines.append('}')
text = '\n'.join(lines) + '\n'
if '--check' in sys.argv:
    if output.read_text() != text:
        sys.exit(f'{output.relative_to(output.parents[3])} is stale. Run Scripts/generate-concatenation.py.')
else:
    output.write_text(text)
